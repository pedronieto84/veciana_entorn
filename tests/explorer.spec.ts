test('ejecucion, comparacion y restauracion desde la web', async ({ page }, info) => {
  await openExplorer(page); await view(page, 'Cambios');
  const run = async (name: string) => {
    await page.locator('.scenario').filter({ has: page.getByRole('heading', { name, exact: true }) }).getByRole('button', { name: 'Preparar' }).click();
    await expect(page.getByRole('dialog')).toBeVisible();
    await page.getByRole('button', { name: 'Confirmar y ejecutar' }).click();
    await expect(page.getByRole('dialog')).not.toBeVisible({ timeout: 30000 });
    await expect(page.getByRole('status')).toBeVisible();
  };
  try {
    await run('Anadir 5 registros');
    await expect(page.getByRole('status')).toContainText('100 → 105');
    await run('Anadir columna');
    await expect(page.getByRole('status')).toContainText('canal_origen');
    await run('Cambiar tipo');
    await expect(page.getByRole('status')).toContainText('text');
    await page.screenshot({ path: `test-results/${info.project.name}-cambios.png`, fullPage: true });
  } finally { await run('Restaurar base'); }
  await view(page, 'Estructura');
  await expect(page.locator('.schema-table tbody tr')).toHaveCount(model.padron.ciudadanos.fields.length);
  await expect(page.locator('.schema-table')).not.toContainText('canal_origen');
});
test('acceso directo, CSRF y rechazo de SQL arbitrario', async ({ request, page }) => {
  const connections = await request.get('/api/connections');
  expect(connections.status()).toBe(200);
  expect((await connections.json()).web).not.toHaveProperty('password');
  await openExplorer(page);
  const session = await (await page.request.get('/api/session')).json();
  const body = { action: 'insert', requestId: randomUUID(), confirm: true };
  expect((await page.request.post('/api/db/padron/scenario', { data: body })).status()).toBe(403);
  const origin = new URL(page.url()).origin;
  expect((await request.post('/api/db/padron/scenario', { headers: { Origin: origin, 'X-CSRF-Token': session.csrf }, data: body })).status()).toBe(403);
  expect((await page.request.post('/api/db/padron/scenario', { headers: { Origin: 'http://otra-pagina.invalid', 'X-CSRF-Token': session.csrf }, data: body })).status()).toBe(403);
  expect((await page.request.post('/api/db/padron/scenario', { headers: { Origin: origin }, data: body })).status()).toBe(403);
  expect((await page.request.post('/api/db/padron/scenario', { headers: { Origin: origin, 'X-CSRF-Token': session.csrf }, data: { ...body, action: 'DROP DATABASE padron' } })).status()).toBe(400);
  expect((await page.request.get('/api/db/padron/table/_lab_state/rows')).status()).toBe(404);
  expect((await page.request.get('/api/db/padron/table/ciudadanos/rows?search=%27%3BDROP%20TABLE%20ciudadanos')).status()).toBe(200);
});
