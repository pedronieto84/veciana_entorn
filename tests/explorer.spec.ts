test('Escoles: seguridad, errores visibles y recuperacion', async ({ page }) => {
  await page.goto('/');
  await page.getByRole('navigation', { name: 'Fuentes', exact: true }).getByRole('button', { name: /Escoles/ }).click();
  await expect(page.locator('.records-table tbody tr')).toHaveCount(20);
  const session = await (await page.request.get('/api/session')).json();
  const origin = new URL(page.url()).origin;
  const body = { action: 'insert', requestId: randomUUID(), confirm: true };
  expect((await page.request.post('/api/source/escoles/scenario', { data: body })).status()).toBe(403);
  expect((await page.request.post('/api/source/escoles/scenario', { headers: { Origin: 'http://otra.invalid', 'X-CSRF-Token': session.csrf }, data: body })).status()).toBe(403);
  expect((await page.request.post('/api/source/escoles/scenario', { headers: { Origin: origin, 'X-CSRF-Token': session.csrf }, data: { ...body, confirm: false } })).status()).toBe(400);
  expect((await page.request.post('/api/source/escoles/scenario', { headers: { Origin: origin, 'X-CSRF-Token': session.csrf }, data: { ...body, action: 'DROP TABLE' } })).status()).toBe(400);
  expect((await page.request.get('/api/source/otra/table/matriculas/rows')).status()).toBe(404);
  const route = '**/api/source/escoles/table/matriculas/rows?*';
  await page.route(route, async response => response.fulfill({ status: 502, contentType: 'application/json', body: JSON.stringify({ error: 'Escoles: la web no responde' }) }));
  await page.getByRole('button', { name: 'Actualizar datos', exact: true }).click();
  await expect(page.getByRole('alert')).toContainText('web no responde');
  await expect(page.locator('.records-table')).toHaveCount(0);
  await page.getByRole('navigation', { name: 'Fuentes', exact: true }).getByRole('button', { name: /Padron/ }).click();
  await expect(page.locator('.records-table tbody tr')).toHaveCount(25);
  await page.unroute(route);
  await page.getByRole('navigation', { name: 'Fuentes', exact: true }).getByRole('button', { name: /Escoles/ }).click();
  await expect(page.locator('.records-table tbody tr')).toHaveCount(20);
  await expect(page.getByRole('alert')).toHaveCount(0);
});